@dataclass
class DAGNode:
    """Individual execution node within the Wake Engine's execution DAG."""
    node_id: str
    phase: str
    input_data: Dict[str, Any]
    output_data: Dict[str, Any]
    duration_us: float
    status: str = "SUCCESS"
    error: Optional[str] = None


@dataclass
class ExecutionTraceDAG:
    """Full execution trace DAG recorded by the Wake Engine during online processing."""
    case_id: str
    email: str
    requested_at: Optional[str]
    audit_at: str
    start_time_iso: str
    total_duration_us: float
    nodes: List[DAGNode] = field(default_factory=list)
    final_status: str = "UNKNOWN"
    step_count: int = 0


@dataclass
class PerturbationCandidate:
    """Counterfactual scenario generated by the Dream Engine."""
    candidate_id: str
    perturbation_type: str
    case_id: str
    perturbed_email: str
    perturbed_request_text: str
    perturbed_audit_at: str
    perturbed_requested_at: Optional[str]
    description: str
    expected_status_invariant: Optional[str] = None


@dataclass
class BenchmarkResult:
    """Execution latency and throughput metrics from the Replay Simulator."""
    total_cases_evaluated: int
    total_elapsed_seconds: float
    microseconds_per_case: float
    cases_per_second: float
    status_distribution: Dict[str, int]


