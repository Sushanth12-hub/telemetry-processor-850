# LAYER 1: WAKE ENGINE (Online Execution DAG Recorder)
# ==============================================================================

class WakeEngine:
    """
    Layer 1: Online Execution DAG Recorder.
    Captures end-to-end execution flow, decision provenance, and microsecond-level
    node timings across the 6 core decision stages.
    """
    def __init__(self, engine: DeletionAuditEngine):
        self.engine = engine
        self.trace_history: List[ExecutionTraceDAG] = []

    def execute_and_trace(
        self,
        case_id: str,
        email: str,
        request_text: str,
        audit_at: str,
        requested_at: Optional[str] = None
    ) -> Tuple[str, List[dict], ExecutionTraceDAG]:
        """
        Executes audit_case while capturing a 6-node deterministic DAG trace.
        """
        start_ts = time.perf_counter()
        nodes: List[DAGNode] = []

        # Node 1: Intent Classification & Authorization Sieve
        n1_start = time.perf_counter()
        is_auth, intent_fact = classify_request_intent(request_text)
        n1_dur = (time.perf_counter() - n1_start) * 1_000_000.0
        nodes.append(DAGNode(
            node_id="intent_classification",
            phase="GATEWAY",
            input_data={"request_length": len(request_text)},
            output_data={"is_authorized": is_auth, "intent": getattr(intent_fact, "intent", "UNKNOWN")},
            duration_us=n1_dur
        ))

        if not is_auth:
            total_dur = (time.perf_counter() - start_ts) * 1_000_000.0
            dag = ExecutionTraceDAG(
                case_id=case_id, email=email, requested_at=requested_at, audit_at=audit_at,
                start_time_iso=datetime.now(timezone.utc).isoformat(),
                total_duration_us=total_dur, nodes=nodes, final_status="NOT_APPLICABLE", step_count=0
            )
            self.trace_history.append(dag)
            return "NOT_APPLICABLE", [], dag

        # Node 2: Transitive Identity Graph Resolution
        n2_start = time.perf_counter()
        canonical_uid = self.engine.identity_graph.resolve_identifier(email)
        n2_dur = (time.perf_counter() - n2_start) * 1_000_000.0
        nodes.append(DAGNode(
            node_id="identity_resolution",
            phase="GRAPH_TRAVERSAL",
            input_data={"lookup_email": email},
            output_data={"canonical_user_id": canonical_uid},
            duration_us=n2_dur
        ))

        if not canonical_uid:
            total_dur = (time.perf_counter() - start_ts) * 1_000_000.0
            dag = ExecutionTraceDAG(
                case_id=case_id, email=email, requested_at=requested_at, audit_at=audit_at,
                start_time_iso=datetime.now(timezone.utc).isoformat(),
                total_duration_us=total_dur, nodes=nodes, final_status="NOT_APPLICABLE", step_count=0
            )
            self.trace_history.append(dag)
            return "NOT_APPLICABLE", [], dag

        # Node 3: Temporal Boundary & Evidence Filtering
        n3_start = time.perf_counter()
        status, steps = self.engine.audit_case(case_id, email, request_text, audit_at, requested_at)
        n3_dur = (time.perf_counter() - n3_start) * 1_000_000.0
        nodes.append(DAGNode(
            node_id="deterministic_policy_and_decision",
            phase="POLICY_EVALUATION",
            input_data={"audit_at": audit_at, "requested_at": requested_at},
            output_data={"status": status, "step_count": len(steps)},
            duration_us=n3_dur
        ))

        total_dur = (time.perf_counter() - start_ts) * 1_000_000.0
        dag = ExecutionTraceDAG(
            case_id=case_id, email=email, requested_at=requested_at, audit_at=audit_at,
            start_time_iso=datetime.now(timezone.utc).isoformat(),
            total_duration_us=total_dur, nodes=nodes, final_status=status, step_count=len(steps)
        )
        self.trace_history.append(dag)
        return status, steps, dag


