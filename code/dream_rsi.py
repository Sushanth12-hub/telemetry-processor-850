# LAYER 4: RSI META-LEARNER (Recursive Self-Improvement Gatekeeper)
# ==============================================================================

class RSIMetaLearner:
    """
    Layer 4: Recursive Self-Improvement Gatekeeper.
    Evaluates candidate heuristic mutations against ground-truth benchmarks.
    Enforces a strict 100% regression bar: zero performance regressions permitted.
    """
    def __init__(self, engine: DeletionAuditEngine):
        self.engine = engine

    def verify_regression_gate(self, sample_reqs_path: str, sample_output_path: str) -> Dict[str, Any]:
        """
        Executes the formal 32-case sample regression gate to certify 100% exact match.
        """
        if not os.path.exists(sample_reqs_path) or not os.path.exists(sample_output_path):
            return {"status": "SKIPPED", "reason": "Sample benchmark files not present."}

        with open(sample_reqs_path, "r", encoding="utf-8") as f:
            reqs = list(csv.DictReader(f))

        with open(sample_output_path, "r", encoding="utf-8") as f:
            expected = {r["case_id"]: r for r in csv.DictReader(f)}

        total = len(reqs)
        status_matches = 0
        exact_matches = 0

        for r in reqs:
            cid = r["case_id"]
            exp = expected[cid]
            exp_status = exp["deletion_status"]
            exp_steps = json.loads(exp["steps_json"])

            pred_status, pred_steps = self.engine.audit_case(
                case_id=cid, email=r["email"], request_text=r["request_text"],
                audit_at=r["audit_at"], requested_at=r.get("requested_at")
            )

            if pred_status == exp_status:
                status_matches += 1
            if pred_status == exp_status and pred_steps == exp_steps:
                exact_matches += 1

        is_promotable = (exact_matches == total)
        return {
            "total_cases": total,
            "status_matches": status_matches,
            "exact_matches": exact_matches,
            "status_accuracy_pct": (status_matches / total) * 100.0,
            "exact_match_pct": (exact_matches / total) * 100.0,
            "promotable": is_promotable
        }


