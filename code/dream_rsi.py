# LAYER 2: EVOLVING WORLD MODEL (In-Memory Replay Simulator)
# ==============================================================================

class ReplaySimulator:
    """
    Layer 2: In-Memory Replay Simulator.
    Decouples policy evaluation from disk and network I/O. Pre-caches indexed
    observations and requests in memory to achieve sub-0.01 ms evaluation latency.
    """
    def __init__(self, engine: DeletionAuditEngine):
        self.engine = engine
        self.cached_cases: List[Dict[str, str]] = []
        self._precache_requests()

    def _precache_requests(self):
        """Loads all available request records into contiguous memory."""
        for fname in ["deletion_requests.csv", "sample_deletion_requests.csv"]:
            p = os.path.join(self.engine.dataset_dir, fname)
            if os.path.exists(p):
                with open(p, "r", encoding="utf-8") as f:
                    self.cached_cases.extend(list(csv.DictReader(f)))

    def benchmark_throughput(self, iterations: int = 1000) -> BenchmarkResult:
        """
        Runs high-speed evaluation loop to benchmark throughput and latency.
        """
        cases_to_run = self.cached_cases if self.cached_cases else [
            {"case_id": "sim_01", "email": "user@example.com", "request_text": "Delete my account", "audit_at": "2026-09-01T00:00:00Z"}
        ]
        total_evals = 0
        status_dist: Dict[str, int] = {}

        t0 = time.perf_counter()
        while total_evals < iterations:
            for c in cases_to_run:
                st, _ = self.engine.audit_case(
                    case_id=c.get("case_id", "c"),
                    email=c.get("email", ""),
                    request_text=c.get("request_text", ""),
                    audit_at=c.get("audit_at", ""),
                    requested_at=c.get("requested_at")
                )
                status_dist[st] = status_dist.get(st, 0) + 1
                total_evals += 1
                if total_evals >= iterations:
                    break

        elapsed = time.perf_counter() - t0
        us_per_case = (elapsed / total_evals) * 1_000_000.0 if total_evals > 0 else 0.0
        cps = total_evals / elapsed if elapsed > 0 else 0.0

        return BenchmarkResult(
            total_cases_evaluated=total_evals,
            total_elapsed_seconds=elapsed,
            microseconds_per_case=us_per_case,
            cases_per_second=cps,
            status_distribution=status_dist
        )


